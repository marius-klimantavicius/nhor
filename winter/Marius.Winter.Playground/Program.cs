using System.Linq;
using Marius.Winter;
using Marius.Winter.Playground.Scenarios;

var backend = args.Contains("--gl") ? RenderBackend.GL : RenderBackend.SW;
var window = new Window(900, 720, "Winter GUI Playground" + (backend == RenderBackend.GL ? " [GL]" : " [SW]"), Theme.Light, backend);
using var profile = new ProfileAndVolume(window);
using var help = new HelpRichDisplayScenario(window);
using var workspace = new ResizableWorkspaceScenario(window);
using var operation = new OperationFeedbackScenario(window);
using var projectBrowser = new ProjectBrowserScenario(window);
using var environmentAndTabs = new EnvironmentAndTabsScenario(window);
using var notes = new NotesScenario(window);
using var installerSetup = new InstallerSetupScenario(window);
using var windowsAndDialogs = new WindowsAndDialogsScenario(window);
using var gallery = new LegacyGallery(window);
using var scenarios = new ScenarioHost(window);
scenarios.AddScenario("Profile and volume", profile.Content);
scenarios.AddScenario("Help and rich display", help.Content);
scenarios.AddScenario("Resizable workspace", workspace.Content);
scenarios.AddScenario("Operation feedback", operation.Content);
scenarios.AddScenario("Existing demos", gallery.Content);
scenarios.AddScenario("Project browser", projectBrowser.Content);
scenarios.AddScenario("Environment and tabs", environmentAndTabs.Content);
scenarios.AddScenario("Notes", notes.Content);
scenarios.AddScenario("Installer setup", installerSetup.Content);
scenarios.AddScenario("Windows and dialogs", windowsAndDialogs.Content);
window.AddChild(scenarios.Content);
window.SetAutoLayout(scenarios.Content);
window.Run();
